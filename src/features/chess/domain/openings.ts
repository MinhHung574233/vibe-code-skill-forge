/** The line as UCI moves from the start position (what the drill compares against). */
export function openingUci(opening: Opening): string[] {
  const chess = new Chess();
  return opening.moves.map(({ san }) => toUci(chess.move(san)));
}

export const openingById = (id: string): Opening | undefined => OPENINGS.find((o) => o.id === id);
