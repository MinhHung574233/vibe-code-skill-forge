export type WordTopic = 'code' | 'web' | 'data' | 'ops' | 'work' | 'security';
export type PartOfSpeech = 'noun' | 'verb' | 'adjective' | 'phrase';

export interface Word {
  id: string;
  term: string;
  pos: PartOfSpeech;
  topic: WordTopic;
  /** Plain-English definition. */
  definition: string;
  /** A realistic sentence from software work, containing the term. */
  example: string;
  /** Vietnamese meaning, short. */
  vi: string;
}

export const TOPIC_LABELS: Record<WordTopic, string> = {
  code: 'Programming',
  web: 'Web & APIs',
  data: 'Data',
  ops: 'DevOps & delivery',
  work: 'Teamwork',
  security: 'Security',
};

const slug = (term: string) => term.toLowerCase().replace(/[^a-z0-9]+/g, '-');

function w(
  term: string,
  pos: PartOfSpeech,
  topic: WordTopic,
  definition: string,
  example: string,
  vi: string,
): Word {
  return { id: slug(term), term, pos, topic, definition, example, vi };
}

